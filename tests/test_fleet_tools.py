def test_mark_lm_day_merges_ranges():
    root = {}
    for d in ['2026-09-03', '2026-09-01', '2026-09-02', '2026-09-10']:
        fleet_scan.mark_lm_day(root, d)
    assert root['lm_cov'] == [['2026-09-01', '2026-09-03'], ['2026-09-10', '2026-09-10']]
    # יום שכבר בטווח — בלי שינוי; יום שמגשר בין טווחים — מיזוג
    fleet_scan.mark_lm_day(root, '2026-09-02')
    for d in ['2026-09-04', '2026-09-05', '2026-09-06', '2026-09-07', '2026-09-08', '2026-09-09']:
        fleet_scan.mark_lm_day(root, d)
    assert root['lm_cov'] == [['2026-09-01', '2026-09-10']]


def test_city_months_and_shift():
    rc = {'100': {'אלעד', 'תל אביב יפו'}, '200': {'באר שבע'}, '300': {'תל אביב יפו'}}
    cm = fleet_moves.city_months({'100': [70, 80], '200': [60, 65], '300': [60, 80]}, rc)
    assert cm == {'אלעד': [70, 80], 'תל אביב יפו': [60, 80], 'באר שבע': [60, 65]}
    assert fleet_moves.city_shift(cm)                       # באר שבע נגמרה לפני אלעד
    assert not fleet_moves.city_shift({'א': [1, 5], 'ב': [3, 9]})   # חופפות


def test_build_keeps_only_movers():
    fleet = {'operators': [
        {'ref': 18, 'name': 'קווים', 'vehicles': [['8130484', '2023-01-02', '2023-10-02', 5.0, 2018, 'סולאריס', None, 'צבורי עיר מפרק'],
                                                  ['111', '2023-01-01', '2026-09-01', 4.0, 2020, 'x', None, 'צבורי עירוני']]},
        {'ref': 15, 'name': 'מטרופולין', 'vehicles': [['8130484', '2023-08-31', '2026-09-01', 6.0, 2018, 'סולאריס', None, 'צבורי עיר מפרק']]},
    ]}
    root = {'vehicles': {
        '18:8130484': ['2023-01-02', '2023-10-02', 900, 190, [1, 2], 0],
        '15:8130484': ['2023-08-31', '2026-09-01', 4000, 700, [3], 0, {'3': [44, 80]}],
        '18:111': ['2023-01-01', '2026-09-01', 100, 50, [1], 0],
    }, 'lm_cov': [['2026-09-01', '2026-09-15']]}
    rc = {'1': {'פתח תקווה', 'תל אביב יפו'}, '2': {'תל אביב יפו'}, '3': {'אלעד', 'תל אביב יפו'}}
    out = fleet_moves.build(fleet, root, rc)
    assert out['since'] == '2023-01-01'
    assert out['cov'] == [['2026-09-01', '2026-09-15']]
    assert set(out['m']) == {'8130484'}                     # 111 שידר אצל חברה אחת בלי שינוי עיר
    assert out['m']['8130484']['18'] == [['פתח תקווה', 'תל אביב יפו'], None]
    assert out['m']['8130484']['15'] == [['אלעד', 'תל אביב יפו'], {'אלעד': [44, 80], 'תל אביב יפו': [44, 80]}]
